#!/usr/bin/env python3
"""Generate the dependency-free C++ catalog and its human-readable inventory."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
data = json.loads((ROOT / "catalog/games.json").read_text(encoding="utf-8"))
entries = data["games"] + data["services"]
assert len(data["games"]) >= 100
assert len({row["id"] for row in entries}) == len(entries)
assert all(row["executables"] or row["steamAppIds"] for row in entries)
excluded = {row["steamAppId"] for row in data["excludedSteamApps"]}
assert not excluded.intersection(app for row in entries for app in row["steamAppIds"])

def wide(value):
    return "L" + json.dumps(value, ensure_ascii=False)

def strings(values):
    return "{" + ", ".join(wide(value) for value in values) + "}"

def code(value):
    return chr(96) + value + chr(96)

cpp = [
    "// Generated by scripts/Generate-Catalog.py from catalog/games.json.",
    "// Reviewed 2026-11-15. Runtime uses no network or external catalog file.",
    '#include "model.hpp"',
    "",
    "namespace mpg {",
    "const std::vector<CatalogEntry>& catalog() {",
    "    static const std::vector<CatalogEntry> entries = {",
]
for row in entries:
    fields = [
        wide(row["id"]), wide(row["name"]), strings(row["executables"]),
        strings(row["pathHints"]), "true" if row["service"] else "false",
        "{" + ", ".join(str(app) for app in row["steamAppIds"]) + "}",
    ]
    cpp.append("        {" + ", ".join(fields) + "},")
cpp.extend(["    };", "    return entries;", "}", "}", ""])

doc = [
    "# Game catalog — November 2026",
    "",
    "Reviewed **15 November 2026**. The compiled catalog contains **110 games "
    "and 10 game-service families**.",
    "",
    "## Selection",
    "",
    "The baseline is [Valve's live Most Played chart]"
    "(https://store.steampowered.com/charts/mostplayed), which ranks Steam apps "
    "by concurrent players. Each of its 100 entries was checked against its "
    "linked Steam store page. The captured app IDs and chart positions are in "
    "[the source snapshot](../catalog/steam-chart-2026-11-15.json).",
    "",
    "Four chart entries are non-game utilities: Wallpaper Engine, Crosshair X, "
    "OBS Studio, and Soundpad. They are excluded from automatic prioritization. "
    "The remaining 96 games are supplemented by 14 major PC games or editions "
    "distributed outside Steam. Those additions are coverage choices; they "
    "have no invented rank or player-count estimate. There is no single "
    "comparable public top-100 ranking across all PC launchers.",
    "",
    "## Detection",
    "",
    "Steam entries use their actual app ID and installed manifest location, "
    "so a title can be supported without guessing its executable filename. "
    "Known executable aliases provide additional coverage for other stores. "
    "Generic filenames such as javaw.exe, Agent.exe, Discovery.exe, and "
    "ShooterGame.exe require a game-specific path hint. They are never global "
    "wildcards. Windows paths are matched without regard to case.",
    "",
    "An empty alias cell means detection uses the Steam installation. It does "
    "not imply that an unverified executable name was fabricated. Alias "
    "compatibility can change with game updates; these are detection rules, "
    "not a claim that every game was installed and play-tested on CI. Add a "
    "missing game from its open window or browse to its EXE.",
    "",
    "Steam and publisher links below establish the game's identity. The "
    "catalog's executable mappings are maintained implementation data, not "
    "a claim that each linked product page documents its filenames. Helpful "
    "publisher filename references include [Fortnite]"
    "(https://www.epicgames.com/help/c-34254770/c-33726977/a10628872?lang=en-US), "
    "[League/Riot](https://support-leagueoflegends.riotgames.com/hc/en-us/articles/43435443937299), "
    "[World of Warcraft](https://us.forums.blizzard.com/en/wow/t/wow-exe-missing/1698586/6), "
    "and [BattlEye](https://www.battleye.com/support/faq/).",
    "",
    "## Games",
    "",
    "| Game | Steam app ID | Known EXE aliases |",
    "| --- | --- | --- |",
]
for row in data["games"]:
    aliases = ", ".join(code(name) for name in row["executables"]) or "Installed Steam game"
    appids = ", ".join(map(str, row["steamAppIds"])) or "Additional PC game"
    doc.append(f'| [{row["name"]}]({row["source"]}) | {appids} | {aliases} |')
doc.extend([
    "",
    "## Game services",
    "",
    "These are specific user-mode service processes, not kernel drivers. "
    "Access denied or an unsupported priority/affinity change is silently "
    "skipped. No service is stopped, patched, injected into, or reconfigured. "
    "Shared Windows hosts such as svchost.exe are excluded. The service "
    "checkbox can turn this entire category off.",
    "",
    "| Service family | Exact EXE names | Required path hint(s) |",
    "| --- | --- | --- |",
])
for row in data["services"]:
    names = ", ".join(code(value) for value in row["executables"])
    hints = ", ".join(code(value) for value in row["pathHints"])
    doc.append(f'| [{row["name"]}]({row["source"]}) | {names} | {hints} |')
doc.extend([
    "",
    "## Maintaining the catalog",
    "",
    "Edit " + code("catalog/games.json") + ", then run " +
    code("python scripts/Generate-Catalog.py") + ". Commit the generated " +
    code("src/catalog.cpp") + " and this inventory together. "
    "CI checks that the generated content is current. Add only verified "
    "game identities, avoid generic bare filenames, and preserve app-ID "
    "and path exclusions for non-game software.",
    "",
])
outputs = {ROOT / "src/catalog.cpp": "\n".join(cpp),
           ROOT / "docs/game-catalog.md": "\n".join(doc)}
parser = argparse.ArgumentParser()
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
for path, content in outputs.items():
    if args.check:
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            raise SystemExit(f"Generated file is out of date: {path.relative_to(ROOT)}")
    else:
        path.write_text(content, encoding="utf-8", newline="\n")
print(f"Catalog verified: {len(data['games'])} games, {len(data['services'])} service families.")
